"""
Remove all .png plot files in out/plt/ (including those in the per-type
subdirectories, e.g. out/plt/bar_plots/). Plots are regenerated by the
relevant plotting workflows.

Run from the repo root: `rmlt clear_plots`
"""

import glob
import os

from react_ml_test_public.helpers.settings import PLOT_DIR

if __name__ == "__main__":

    png_files = sorted(glob.glob(f"{PLOT_DIR}/**/*.png", recursive=True))
    n_files = len(png_files)

    if n_files == 0:
        print(f"No .png files found in {PLOT_DIR}.")
        raise SystemExit

    prompt = (f"Are you sure you want to remove {n_files} .png file"
              f"{'s' if n_files != 1 else ''} in {PLOT_DIR}? (y/n): ")
    response = input(prompt).strip().lower()

    if response not in ("y", "yes"):
        print("Aborting - no files removed.")
        raise SystemExit

    for png_fpath in png_files:
        os.remove(png_fpath)

    print(f"Removed {n_files} .png file{'s' if n_files != 1 else ''} from {PLOT_DIR}.")
